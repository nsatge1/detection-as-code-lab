"""Build the MITRE ATT&CK coverage report from the rule tags.

Writes two files:

    docs/coverage.md                    rule catalog + coverage per tactic
    docs/attack_navigator_layer.json    layer to open in ATT&CK Navigator
                                        (https://mitre-attack.github.io/attack-navigator/)

Usage:
    python -m scripts.coverage_report           # write the files
    python -m scripts.coverage_report --check   # CI: fail if the files are out of date
"""

from __future__ import annotations

import argparse
import json
import sys
from collections import defaultdict
from pathlib import Path

from scripts.detection_engine import Rule, load_rules

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"

# Techniques used in this repository: name and tactics in ATT&CK Enterprise v20.
# v20 (October 2026) split "Defense Evasion" into "Stealth" and "Defense Impairment".
ATTACK_VERSION = "20"
TECHNIQUES: dict[str, tuple[str, tuple[str, ...]]] = {
    "T1003.001": ("OS Credential Dumping: LSASS Memory", ("credential-access",)),
    "T1003.002": ("OS Credential Dumping: Security Account Manager", ("credential-access",)),
    "T1027.010": ("Obfuscated Files or Information: Command Obfuscation", ("stealth",)),
    "T1053.005": (
        "Scheduled Task/Job: Scheduled Task",
        ("execution", "persistence", "privilege-escalation"),
    ),
    "T1059.001": ("Command and Scripting Interpreter: PowerShell", ("execution",)),
    "T1059.004": ("Command and Scripting Interpreter: Unix Shell", ("execution",)),
    "T1078.004": (
        "Valid Accounts: Cloud Accounts",
        ("initial-access", "persistence", "privilege-escalation", "stealth"),
    ),
    "T1098": ("Account Manipulation", ("persistence", "privilege-escalation")),
    "T1105": ("Ingress Tool Transfer", ("command-and-control",)),
    "T1204.002": ("User Execution: Malicious File", ("execution",)),
    "T1490": ("Inhibit System Recovery", ("impact",)),
    "T1566.001": ("Phishing: Spearphishing Attachment", ("initial-access",)),
    "T1685": ("Disable or Modify Tools", ("defense-impairment",)),
    "T1685.002": ("Disable or Modify Tools: Disable or Modify Cloud Log", ("defense-impairment",)),
    "T1685.005": ("Disable or Modify Tools: Clear Windows Event Logs", ("defense-impairment",)),
}

# Kill-chain order of ATT&CK Enterprise tactics.
TACTICS = [
    "reconnaissance",
    "resource-development",
    "initial-access",
    "execution",
    "persistence",
    "privilege-escalation",
    "stealth",
    "defense-impairment",
    "credential-access",
    "discovery",
    "lateral-movement",
    "collection",
    "command-and-control",
    "exfiltration",
    "impact",
]

LEVEL_SCORE = {"informational": 1, "low": 1, "medium": 2, "high": 3, "critical": 4}


def technique_url(technique: str) -> str:
    return f"https://attack.mitre.org/techniques/{technique.replace('.', '/')}/"


def build_markdown(rules: list[Rule]) -> str:
    techniques = sorted({t for rule in rules for t in rule.techniques})
    by_tactic: dict[str, set[str]] = defaultdict(set)
    for technique in techniques:
        for tactic in TECHNIQUES[technique][1]:
            by_tactic[tactic].add(technique)

    lines = [
        "# Detection coverage",
        "",
        "> Generated by `python -m scripts.coverage_report`. Do not edit by hand.",
        "",
        f"**{len(rules)} rules** cover **{len(techniques)} ATT&CK techniques** "
        f"in **{len(by_tactic)} tactics** (MITRE ATT&CK Enterprise v{ATTACK_VERSION}).",
        "",
        "## Coverage by tactic",
        "",
        "| Tactic | Techniques |",
        "|---|---|",
    ]
    for tactic in TACTICS:
        if tactic in by_tactic:
            names = ", ".join(sorted(by_tactic[tactic]))
            title = tactic.replace("-", " ").title().replace(" And ", " and ")
            lines.append(f"| {title} | {names} |")

    lines += [
        "",
        "## Rule catalog",
        "",
        "| Rule | Level | Log source | ATT&CK |",
        "|---|---|---|---|",
    ]
    for rule in sorted(rules, key=lambda r: (-LEVEL_SCORE[r.level], r.title)):
        source = "/".join(
            rule.logsource[k] for k in ("product", "category", "service") if k in rule.logsource
        )
        attack = ", ".join(f"[{t}]({technique_url(t)})" for t in rule.techniques)
        path = rule.path.relative_to(ROOT).as_posix()
        lines.append(f"| [{rule.title}](../{path}) | {rule.level} | `{source}` | {attack} |")

    lines += ["", "## Techniques", "", "| ID | Name | Rules |", "|---|---|---|"]
    for technique in techniques:
        count = sum(technique in r.techniques for r in rules)
        name = TECHNIQUES[technique][0]
        lines.append(f"| [{technique}]({technique_url(technique)}) | {name} | {count} |")
    return "\n".join(lines) + "\n"


def build_navigator_layer(rules: list[Rule]) -> dict:
    per_technique: dict[str, list[Rule]] = defaultdict(list)
    for rule in rules:
        for technique in rule.techniques:
            per_technique[technique].append(rule)

    techniques = []
    for technique, matching in sorted(per_technique.items()):
        techniques.append(
            {
                "techniqueID": technique,
                "score": max(LEVEL_SCORE[r.level] for r in matching),
                "comment": "; ".join(sorted(r.title for r in matching)),
                "enabled": True,
            }
        )
    return {
        "name": "detection-as-code-lab coverage",
        "versions": {"attack": ATTACK_VERSION, "layer": "4.5", "navigator": "5.1.0"},
        "domain": "enterprise-attack",
        "description": "Techniques covered by the Sigma rules in detection-as-code-lab. "
        "Score = highest rule level (1 low ... 4 critical).",
        "techniques": techniques,
        "gradient": {"colors": ["#fff3b0", "#f4a259", "#bc4b51"], "minValue": 1, "maxValue": 4},
        "legendItems": [
            {"label": "low / medium", "color": "#fff3b0"},
            {"label": "high", "color": "#f4a259"},
            {"label": "critical", "color": "#bc4b51"},
        ],
        "showTacticRowBackground": True,
        "selectSubtechniquesWithParent": False,
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--check", action="store_true", help="fail if docs/ is out of date")
    args = parser.parse_args(argv)

    rules = load_rules(ROOT / "detections")
    unknown = sorted({t for r in rules for t in r.techniques} - set(TECHNIQUES))
    if unknown:
        print(f"Add these techniques to TECHNIQUES in {Path(__file__).name}: {', '.join(unknown)}")
        return 1

    outputs = {
        DOCS / "coverage.md": build_markdown(rules),
        DOCS / "attack_navigator_layer.json": json.dumps(build_navigator_layer(rules), indent=2) + "\n",
    }

    if args.check:
        stale = [p for p, content in outputs.items() if not p.exists() or p.read_text() != content]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date. Run: python -m scripts.coverage_report")
        return 1 if stale else 0

    DOCS.mkdir(exist_ok=True)
    for path, content in outputs.items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
